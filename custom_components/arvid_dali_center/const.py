# Скорость нативной кнопочной рампы «плавно ярче/темнее» (dpid25/26): стандартная DALI-таблица
# fadeRate → ШАГ/С по шкале arc power (254 уровня ≈ 255). Шаг DALI ≈ уровень яркости HA (0..255),
# маппинг 1:1. Используется для ЭМПИРИЧЕСКОЙ оценки яркости от времени удержания (баг2, без writeDev).
# См. docs/PLAN_PANEL_HOLD_DIM.md. Значения совпадают с FADE_RATE_OPTS карты.
PANEL_FADE_RATE_STEPS = {
    1: 358, 2: 253, 3: 179, 4: 127, 5: 89, 6: 63, 7: 45, 8: 32,
    9: 22, 10: 16, 11: 11, 12: 8, 13: 5.6, 14: 4, 15: 2.8,
}
PANEL_DEFAULT_FADE_RATE = 8   # «комфортно» (32 шаг/с) — когда у цели fadeRate не задан в ParamStore
# Калибровочный коэффициент скорости рампы (эмпирика удержания): реальный драйвер рампит быстрее
# таблицы. Откалибровано ЗАМЕРОМ на железе (2026-07-06): fadeRate 6, ход 100%→1% (~252 уровня HA)
# за 2.30с → реальная скорость ~110 уровней/с; таблица[6]=63 → gain = 110/63 ≈ 1.74. Быстрее даже
# IEC 62386 (~89 для F6), поэтому именно коэффициент, а не сдвиг таблицы. См. docs/PLAN_PANEL_HOLD_DIM.
PANEL_HOLD_RATE_GAIN = 1.74
