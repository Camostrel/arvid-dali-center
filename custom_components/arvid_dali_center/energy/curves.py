DEFAULT_CURVE = "linear"


# ── ПОЛЬЗОВАТЕЛЬСКИЕ КРИВЫЕ ИЗ ФАЙЛА (2026-08-13) ────────────────────────────────────
# ЗАЧЕМ. Кривая — свойство КОНКРЕТНОГО драйвера, и на каждом объекте свои светильники (на
# школе №45 их два типа: «большие» и «маленькие»). Держать их в коде значит выпускать версию
# ради таблицы, снятой пусконаладчиком на объекте. Поэтому таблица живёт в ВИДИМОМ файле,
# который человек заполняет сам (правило пользователя 2026-08-11: то, что заполняет человек,
# лежит на видном месте, а не скрытой точкой).
#
# ФОРМАТ (`/config/arvid_curves/curves.yaml`) — точки задаются В ТЕХ ЕДИНИЦАХ, В КОТОРЫХ МЕРЯЮТ:
#
#   curves:
#     big:
#       label: "Большие светильники"
#       full_w: 60.0            # ватты при 100% (можно опустить — возьмём максимум точек)
#       standby_w: 0.4          # ватты при выключенной лампе (обычно 0)
#       points:                 # «яркость % → ватты» с ваттметра
#         10: 5.2
#         30: 18.4
#         100: 60.0
#
# Нормировку в доли (0..1) делаем САМИ — пусконаладчику не приходится ничего пересчитывать.
# ⚠ Встроенные `linear`/`lbs` остаются: файла нет — поведение как раньше. Совпало имя —
# пользовательская побеждает, но об этом пишем предупреждение (иначе подмена была бы тихой).
USER_CURVES_FILE = "arvid_curves/curves.yaml"     # относительно /config


def parse_user_curves(raw: dict) -> tuple[dict, list[str]]:
    """Разобрать содержимое файла → (кривые в нашем формате, список проблем).

    Проблемы НЕ глушим и не выбрасываем молча: кривая с опечаткой означает неверный
    энергоучёт по всему типу светильников, и человек должен это увидеть, а не гадать.
    """
    out: dict[str, dict] = {}
    problems: list[str] = []
    if not isinstance(raw, dict):
        return out, ["файл пуст или не является словарём"]
    curves = raw.get("curves")
    if not isinstance(curves, dict) or not curves:
        return out, ["нет секции `curves` или она пуста"]

    for cid, body in curves.items():
        cid = str(cid).strip()
        if not isinstance(body, dict):
            problems.append(f"{cid}: описание кривой должно быть словарём")
            continue
        pts_raw = body.get("points")
        if not isinstance(pts_raw, dict) or not pts_raw:
            problems.append(f"{cid}: нет точек `points` (яркость % → ватты)")
            continue
        try:
            pairs = sorted((float(k), float(v)) for k, v in pts_raw.items())
        except (TypeError, ValueError):
            problems.append(f"{cid}: точки должны быть числами «яркость: ватты»")
            continue
        if any(x < 0 or x > 100 for x, _ in pairs):
            problems.append(f"{cid}: яркость задаётся в процентах 0..100")
            continue
        if any(w < 0 for _, w in pairs):
            problems.append(f"{cid}: мощность не может быть отрицательной")
            continue
        full_w = body.get("full_w")
        try:
            full = float(full_w) if full_w is not None else max(w for _, w in pairs)
        except (TypeError, ValueError):
            problems.append(f"{cid}: `full_w` должен быть числом (ватты при 100%)")
            continue
        if full <= 0:
            problems.append(f"{cid}: `full_w` (или максимум точек) равен нулю — делить не на что")
            continue
        # нормируем: проценты → доли, ватты → доли полной мощности
        points = [(x / 100.0, w / full) for x, w in pairs]
        if points[0][0] > 0:
            points.insert(0, (0.0, 0.0))      # ноль яркости = ноль мощности (standby отдельно)
        if points[-1][0] < 1.0:
            points.append((1.0, 1.0))          # выше последней точки держим полку 100%
            problems.append(f"{cid}: нет точки на 100% — достроил линейно до полной мощности")
        try:
            standby = float(body.get("standby_w") or 0.0)
        except (TypeError, ValueError):
            problems.append(f"{cid}: `standby_w` должен быть числом")
            standby = 0.0
        out[cid] = {
            "label": str(body.get("label") or cid),
            "standby_w": standby,
            "points": points,
            "source": str(body.get("source") or f"файл {USER_CURVES_FILE}"),
            "full_w": full,
            "user": True,
        }
    return out, problems


def apply_user_curves(user: dict) -> list[str]:
    """Добавить пользовательские кривые к встроенным. Возврат — предупреждения о подмене."""
    warns = []
    for cid in list(CURVES):
        if CURVES[cid].get("user"):
            CURVES.pop(cid)                    # прежние пользовательские снимаем: файл — истина
    for cid, curve in user.items():
        if cid in CURVES:
            warns.append(f"кривая {cid!r} из файла ПЕРЕКРЫВАЕТ встроенную")
        CURVES[cid] = curve
    return warns


def curve_list() -> list[dict]:
    """Список кривых для UI (карточка предлагает выбор в параметрах лампы)."""
    return [{"id": cid, "label": c["label"], "source": c.get("source", "")}
            for cid, c in CURVES.items()]


def _shape(curve: dict, frac: float) -> float:
    """Доля полной мощности при доле яркости `frac` (кусочно-линейная интерполяция)."""
    pts = curve["points"]
    if frac <= pts[0][0]:
        return pts[0][1]
    for i in range(1, len(pts)):
        x1, y1 = pts[i]
        if frac <= x1:
            x0, y0 = pts[i - 1]
            if x1 == x0:                      # защита от деления на ноль (кривая-ступенька)
                return y1
            k = (frac - x0) / (x1 - x0)
            return y0 + k * (y1 - y0)
    return pts[-1][1]                          # выше последней точки — держим полку


def power_at(model: str | None, power_w: float | None, frac: float) -> float:
    """Мощность лампы (Вт) при доле яркости `frac` (0 = выключена).

    `power_w` не задан → 0 Вт: энергию по такой лампе НЕ копим (её наработка копится всё равно;
    непокрытые лампы видно в отчёте — принцип «проблемы видимы», не подставляем выдуманное число).
    Неизвестная `model` → дефолтная (линейная) кривая + предупреждение в лог.
    """
    curve = CURVES.get(model or DEFAULT_CURVE)
    if curve is None:
        _LOGGER.warning("энергия: неизвестная кривая %r → считаю по %r", model, DEFAULT_CURVE)
        curve = CURVES[DEFAULT_CURVE]
    if frac <= 0:
        return float(curve.get("standby_w", 0.0))   # выключена: дежурное потребление (обычно 0)
    if not power_w:
        return 0.0
    return float(power_w) * _shape(curve, min(1.0, float(frac)))
