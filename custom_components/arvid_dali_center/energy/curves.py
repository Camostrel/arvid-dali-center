"""Кривые «яркость → мощность» по типам драйверов (расчётный энергоучёт).

Зачем (docs/ENERGY_CALC_MODEL.md): энергию считаем САМИ, опираясь на ЯРКОСТЬ (её шлюз знает
достоверно), а не на его энергочисло — оно недостоверно в принципе (шлюз не измеряет: он либо
ретранслирует энергобанк драйвера, либо выдумывает; снаружи неразличимо).

Модель:
    P(вкл)  = power_w × curve(доля_яркости)     # power_w — полная мощность ЛАМПЫ при 100%
    P(выкл) = standby_w                          # по замерам = 0

Разделение ответственности (ключевое для масштаба 4400 ламп):
- **форму** кривой задаёт ДРАЙВЕР (как он переводит уровень DALI в ток) → общая на объект
  (драйвер обычно один) → кривых единицы;
- **масштаб** (полная мощность в ваттах) задаёт ЛАМПА (длина ленты/модель) → своя у каждой.

⚠ Мелкие лампы (дизайнерские в вестибюлях) на ТОМ ЖЕ драйвере могут требовать своей кривой:
собственное потребление драйвера не масштабируется с нагрузкой, на малой лампе его доля больше
(сильнее провал на низах). Поэтому `model` задаётся НА ЛАМПУ, а не на объект.

Новые кривые заводятся по замеру реле на входе 230 В (методика — docs/ENERGY_CALC_MODEL.md §5),
таблицы — docs/DRIVER_POWER_CURVES.md.
"""

