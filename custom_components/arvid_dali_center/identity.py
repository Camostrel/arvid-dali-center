"""Идентичность устройства — ЧЕМ ключуются имя, параметры, сущности и энергоучёт.

━━ ЗАЧЕМ ДВА РЕЖИМА ━━
Штатный ключ — серийник (`devSn`): он не зависит от адреса, поэтому имя едет за устройством
при перенумерации. Но обещание держит ШЛЮЗ, а он врёт: на объектах ловится перекрёст серийников
между `dali` и `dali2` (docs/DEVSN_CROSSWIRE.md), прошивкой не лечится, а у ламп DALI-1
серийника может не быть вовсе. Поэтому предусмотрен второй режим, где идентичность — физическая
координата на шине, а серийник остаётся СПРАВОЧНЫМ полем и ничего не ключует.

    режим `devsn` (по умолчанию)  — ключ = devSn, поведение как было всегда
    режим `addr`                  — ключ = addr:<gwSn>:<канал>:<пространство>:<адрес>

Разбор модели, цена и план — **docs/ADDRESS_IDENTITY.md**.

━━ ПОЧЕМУ ОДНА ФУНКЦИЯ, А НЕ ВТОРАЯ РЕАЛИЗАЦИЯ ━━
Соблазн «сделать параллельный метод целиком» велик, но у проекта есть свой счёт по этому классу:
весь §F реестра долгов — «фикс доехал до одного вызывающего из двух». Две копии логики расходятся
молча и через месяц. Поэтому ветвление ровно одно — здесь; параллельны только ДАННЫЕ.

━━ ПРАВИЛА КЛЮЧА ━━
1. Префикс `addr:` ОБЯЗАТЕЛЕН. Ключи двух режимов не должны пересекаться никогда: корзина HA
   хранит удалённые записи бессрочно (docs/DEBT.md §T5) и воскрешает их по `unique_id` — без
   префикса возврат режима мог бы поднять чужое.
2. В ключе — АДРЕСНОЕ ПРОСТРАНСТВО (`dali`/`dali2`), а не `devType`: у ламп и у датчиков/панелей
   адреса 0..63 независимы, а движение `0201` и освещённость `0202` на одном адресе — это ОДНО
   физическое устройство с двумя функциями.
3. ⚠ Из п.2 следует: ключ устройства НЕ различает движение и освещённость. Там, где различать
   ОБЯЗАТЕЛЬНО (предпочтение активности, записанная конфигурация функции), ключ строится через
   `function_key()` — идентичность ПЛЮС `devType`. В режиме `devsn` это тот же принцип: серийник
   у пары общий, поэтому `SensorPrefStore` ключуется `devSn:devType` (Fix L, v1.1.6). Потерять
   `devType` легко, а отказ будет ТИХИМ: тумблер одной функции начнёт управлять обеими.

Модуль ЧИСТЫЙ (stdlib), без Home Assistant — чтобы его можно было покрыть тестами.
"""

from __future__ import annotations

# ── режимы ───────────────────────────────────────────────────────────────────
MODE_DEVSN = "devsn"          # штатный: ключ — серийник устройства
MODE_ADDR = "addr"            # адресный: ключ — координата на шине
MODES = (MODE_DEVSN, MODE_ADDR)
DEFAULT_MODE = MODE_DEVSN     # ⚠ по умолчанию НИЧЕГО не меняется

ADDR_PREFIX = "addr:"

# Типы «управляющих устройств» DALI (лампы). Единый источник: раньше список жил в
# coordinator.py, и любая вторая копия неизбежно разошлась бы с этой.
LIGHT_TYPES = {"0101", "0102", "0103", "0104", "0105", "0106"}


def address_space(devtype) -> str:
    """Адресное пространство DALI: `dali` (лампы) или `dali2` (датчики/панели).

    У них РАЗНЫЕ наборы коротких адресов: адрес 5 у лампы и адрес 5 у датчика — разные
    устройства, а не конфликт. Так это называет и сам шлюз в `AddrConflicts`.
    """
    return "dali" if str(devtype) in LIGHT_TYPES else "dali2"


def addr_key(gw_sn: str, channel, address, devtype) -> str | None:
    """Координата устройства как ключ идентичности. `None`, если координата неполная.

    Неполная координата — это не «возьмём что есть»: устройство без адреса мы просто не знаем,
    и придумывать ему ключ означало бы склеить в одну запись всех безадресных (ровно так
    когда-то склеивались устройства с сентинелом `00000000FFFFFFFF`).
    """
    if not gw_sn or channel is None or address is None:
        return None
    return f"{ADDR_PREFIX}{str(gw_sn).upper()}:{channel}:{address_space(devtype)}:{address}"


def identity_key(mode: str, gw_sn: str, dev: dict) -> str | None:
    """ЕДИНСТВЕННАЯ точка ветвления идентичности. `None` = ключа нет, хранить нечем.

    В режиме `devsn` возвращает серийник как есть (проверку годности делает вызывающий —
    `is_valid_devsn`, чтобы этот модуль остался чистым от знания о сентинелах вендора).
    """
    if mode == MODE_ADDR:
        return addr_key(gw_sn, dev.get("channel"), dev.get("address"), dev.get("devType"))
    sn = dev.get("devSn")
    return sn or None


def function_key(identity: str | None, devtype) -> str | None:
    """Ключ ФУНКЦИИ устройства (см. правило 3 в шапке): идентичность + `devType`.

    Нужен там, где движение `0201` и освещённость `0202` обязаны жить раздельно, хотя
    физически это одно устройство: предпочтение активности и записанная конфигурация функции.
    """
    if not identity or devtype is None:
        return None
    return f"{identity}:{devtype}"


def is_addr_key(key: str | None) -> bool:
    """Ключ построен адресным режимом? Нужно для диагностики и сторожей в тестах."""
    return bool(key) and str(key).startswith(ADDR_PREFIX)


def normalize_mode(value) -> str:
    """Привести значение режима к известному. Неизвестное — это НЕ повод падать, но и не повод
    молча угадывать: возвращаем режим по умолчанию, а вызывающий обязан сказать об этом в лог."""
    v = str(value or "").strip().lower()
    return v if v in MODES else DEFAULT_MODE
