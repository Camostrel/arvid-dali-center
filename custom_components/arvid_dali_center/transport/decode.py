from __future__ import annotations

DEVTYPE = {
    "0101": "Свет(моно)", "0102": "Свет CCT", "0103": "Свет RGB", "0104": "Свет XY",
    "0105": "Свет RGBW", "0106": "Свет RGBWA", "0107": "Аварийный",
    "0201": "Датч.движения", "0202": "Датч.освещ.",
    "0300": "Поворот.панель", "0302": "Панель2", "0304": "Панель4",
    "0306": "Панель6", "0308": "Панель8", "FFFF": "Шлюз",
}
# Состояние датчика движения — МАШИННАЯ форма (v1.2.45, решение пользователя 2026-08-06).
# Было по-русски («ДВИЖЕНИЕ»/«свободно»/…), из-за чего автоматизации и внешние потребители
# сравнивали кириллицу. ⚠ Это ЗНАЧЕНИЕ СОСТОЯНИЯ сущности: смена рвёт историю recorder на
# переходе и ломает сравнения по старым строкам (в т.ч. в соседнем visual_interface —
# правится отдельно, этот репозиторий его не трогает).
MOTION = {1: "no_motion", 2: "motion", 3: "vacant", 4: "occupied", 5: "occupied_hold"}


def devtype_name(dt: str) -> str:
    return DEVTYPE.get(dt, dt or "?")


def is_valid_devsn(sn) -> bool:
    """devSn валиден, если непустой и НЕ вырожденный (один повторяющийся байт —
    сентинел сбоя прошивки шлюза, напр. '2525…' = 0x25*N, '0000…'). Нужен, чтобы
    мусорный devSn не перезаписывал валидный в кеше: иначе ломается идентичность
    сущностей (карточка не находит entity_id, плодятся «зомби»-устройства)."""
    s = str(sn or "").strip()
    if len(s) < 4 or len(s) % 2:
        return False
    # devSn — hex по байтам: если все байт-пары одинаковы → вырожденный сентинел
    pairs = {s[i:i + 2] for i in range(0, len(s), 2)}
    return len(pairs) > 1
